
CREATE TABLE USUARIO (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    USUARIO VARCHAR(50) NOT NULL UNIQUE,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    SENHA VARCHAR(255) NOT NULL,
    FOTO VARCHAR(255)
);


CREATE TABLE EVENTO (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    SOBRE VARCHAR(1000),
    DATA_EVENTO DATE NOT NULL,
    INICIO TIME NOT NULL,
    FIM TIME,
    VAGAS INT NOT NULL,
    PUBLICO BOOLEAN NOT NULL DEFAULT TRUE,
    CANCELADO BOOLEAN NOT NULL DEFAULT FALSE,
    CRIADOR_ID INT NOT NULL,
    RUA VARCHAR(255),
    NUMERO VARCHAR(20),
    BAIRRO VARCHAR(100),
    CIDADE VARCHAR(100),
    ESTADO VARCHAR(2),
    CEP VARCHAR(10),
    FOREIGN KEY (CRIADOR_ID) REFERENCES USUARIO(ID)
);

CREATE TABLE INSCRICAO (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    USUARIO_ID INT NOT NULL,
    EVENTO_ID INT NOT NULL,
    DATA_INSCRICAO TIMESTAMP NOT NULL,
    UNIQUE (USUARIO_ID, EVENTO_ID),
    FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID) ON DELETE CASCADE,
    FOREIGN KEY (EVENTO_ID) REFERENCES EVENTO(ID) ON DELETE CASCADE
);

CREATE TABLE AVALIACAO (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    USUARIO_ID INT NOT NULL,
    EVENTO_ID INT NOT NULL,
    NOTA INT NOT NULL CHECK (NOTA BETWEEN 1 AND 5),
    COMENTARIO VARCHAR(1000),
    DATA_AVALIACAO TIMESTAMP NOT NULL,
    UNIQUE (USUARIO_ID, EVENTO_ID),
    FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID) ON DELETE CASCADE,
    FOREIGN KEY (EVENTO_ID) REFERENCES EVENTO(ID) ON DELETE CASCADE
);


CREATE TABLE CATEGORIA (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE EVENTO_CATEGORIA (
    EVENTO_ID INT NOT NULL,
    CATEGORIA_ID INT NOT NULL,
    PRIMARY KEY (EVENTO_ID, CATEGORIA_ID),
    FOREIGN KEY (EVENTO_ID) REFERENCES EVENTO(ID) ON DELETE CASCADE,
    FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIA(ID) ON DELETE CASCADE
);

CREATE TABLE IMAGEM_EVENTO (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    EVENTO_ID INT NOT NULL,
    CAMINHO VARCHAR(500) NOT NULL,
    FOREIGN KEY (EVENTO_ID) REFERENCES EVENTO(ID) ON DELETE CASCADE
);

CREATE TABLE FAVORITO (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    USUARIO_ID INT NOT NULL,
    EVENTO_ID INT NOT NULL,
    UNIQUE (USUARIO_ID, EVENTO_ID),
    FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID) ON DELETE CASCADE,
    FOREIGN KEY (EVENTO_ID) REFERENCES EVENTO(ID) ON DELETE CASCADE
);

CREATE TABLE PRESENCA (
    USUARIO_ID INT NOT NULL,
    EVENTO_ID INT NOT NULL,
    DATA_CONFIRMACAO TIMESTAMP NOT NULL,
    PRIMARY KEY (USUARIO_ID, EVENTO_ID),
    FOREIGN KEY (USUARIO_ID, EVENTO_ID) REFERENCES INSCRICAO(USUARIO_ID, EVENTO_ID) ON DELETE CASCADE
);
